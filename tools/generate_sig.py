"""Generate deterministic name-only data. Never fetch upstream or modify profiles."""
from pathlib import Path
import argparse
import json
import subprocess
from tempfile import NamedTemporaryFile
from sig_tables import TABLES, read_table

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
parser.add_argument('--output', type=Path, default=ROOT / 'src/catalogs/sig/sig.generated.inc',
                    help='Output file. Its parent can be passed as NABTOOLS_SIG_DATA_DIR.')
args = parser.parse_args()
profiles = json.loads((ROOT / 'tools/sig_profiles.json').read_text(encoding='utf8'))
source = ROOT / 'bluetooth-SIG'

def git(directory, *args):
    return subprocess.check_output(['git', '--no-optional-locks', '-C', str(directory), *args],
                                   encoding='utf-8').strip()

if not (source / '.git').exists():
    raise SystemExit('Run git submodule update --init --checkout -- bluetooth-SIG before generating tables.')
mode, pinned, stage, path = git(ROOT, 'ls-files', '--stage', '--', 'bluetooth-SIG').split()
revision = git(source, 'rev-parse', 'HEAD')
if mode != '160000' or stage != '0' or revision != pinned:
    raise SystemExit('Bluetooth SIG checkout differs from the pinned submodule commit.')
if git(source, 'status', '--porcelain', '--untracked-files=no'):
    raise SystemExit('Bluetooth SIG submodule has modified tracked files.')
tables = {name: read_table(source, name) for name in TABLES}

def quote(name):
    return json.dumps(name, ensure_ascii=True)

parts = ['// Generated by tools/generate_sig.py; upstream notices remain in bluetooth-SIG/.',
         f'// Source submodule {revision}; names only.',
         '// COMMON/EXTENDED are curated coverage, not population statistics.']
counts = {}
for profile in (1, 2, 3):
    parts.append(('#if' if profile == 1 else '#elif') + f' NABTOOLS_SIG_PROFILE == {profile}')
    counts[profile] = {}
    for table, rows in tables.items():
        selected = rows
        if profile < 3 and table == 'company':
            ids = set(profiles['common_company_ids'])
            if profile == 2:
                ids.update(code for code, name in rows.items() if any(t.lower() in name.lower() for t in profiles['extended_name_terms']))
            missing = ids - rows.keys()
            if missing:
                raise ValueError(f'Missing company IDs: {sorted(missing)}')
            selected = {code: rows[code] for code in ids}
        elif profile == 1 and table != 'ad_type':
            ids = profiles.get(f'common_{table}_ids', [])
            missing = set(ids) - rows.keys()
            if missing: raise ValueError(f'Missing {table} IDs: {sorted(missing)}')
            selected = {code: rows[code] for code in ids}
        counts[profile][table] = len(selected)
        if not selected: continue
        parts.append(f'static constexpr Entry {table}_names[] = {{')
        parts.extend(f'    {{{code}, {quote(name)}}},' for code, name in sorted(selected.items()))
        parts.append('};')
parts.append('#endif')
result = '\n'.join(parts) + '\n'
target = args.output
if args.check:
    if not target.exists() or target.read_text(encoding='utf8') != result:
        raise SystemExit('SIG derivatives differ; regenerate and inspect the source/profile change')
elif not target.is_file() or target.read_text(encoding='utf8') != result:
    target.parent.mkdir(parents=True, exist_ok=True)
    with NamedTemporaryFile(mode='w', encoding='utf8', newline='\n', dir=target.parent,
                            delete=False) as output:
        temporary = Path(output.name)
        try:
            output.write(result)
            output.close()
            temporary.replace(target)
        finally:
            temporary.unlink(missing_ok=True)
print(json.dumps(counts))
